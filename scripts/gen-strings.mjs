#!/usr/bin/env node
// Generates shared/.../i18n/S.kt from the web locale files merged with i18n/mobile.{en,id}.json.
// Usage: node scripts/gen-strings.mjs [path/to/web/locales]   (default ../rencana-web/i18n/locales)
// Pure Node, no dependencies. Rerun whenever web locales or mobile.*.json change.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const webDir = resolve(root, process.argv[2] ?? '../rencana-web/i18n/locales')
const outFile = resolve(root, 'shared/src/commonMain/kotlin/com/zuramai/rencana/i18n/S.kt')

const fail = (msg) => { console.error(`gen-strings: ${msg}`); process.exit(1) }
const load = (p) => JSON.parse(readFileSync(p, 'utf8'))

function flatten(obj, prefix = '', out = new Map()) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (v !== null && typeof v === 'object') flatten(v, key, out)
    else if (typeof v === 'string') out.set(key, v)
    else fail(`non-string value at ${key}`)
  }
  return out
}

function merge(web, mobile, lang) {
  const out = new Map(web)
  for (const [k, v] of mobile) {
    if (out.has(k)) fail(`duplicate key "${k}" in web ${lang} and mobile ${lang}`)
    out.set(k, v)
  }
  return out
}

const langs = {}
for (const lang of ['en', 'id']) {
  langs[lang] = merge(flatten(load(resolve(webDir, `${lang}.json`))), flatten(load(resolve(root, `i18n/mobile.${lang}.json`))), lang)
}

const missing = []
for (const k of langs.en.keys()) if (!langs.id.has(k)) missing.push(`${k} (missing in id)`)
for (const k of langs.id.keys()) if (!langs.en.has(k)) missing.push(`${k} (missing in en)`)
if (missing.length) fail(`incomplete keys:\n  ${missing.join('\n  ')}`)

const constName = (key) => key.split('.').map((seg) => seg.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()).join('_')
const kt = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n') + '"'
const plural = (s) => { const p = s.split(' | '); return p.length === 3 ? p : null }

const entries = []
const seen = new Map()
function add(name, en, id, key) {
  if (seen.has(name)) fail(`constant name clash: ${name} (${key} vs ${seen.get(name)})`)
  seen.set(name, key)
  entries.push(`    ${name}(${kt(en)}, ${kt(id)})`)
}
for (const [key, en] of langs.en) {
  const id = langs.id.get(key)
  const pe = plural(en), pi = plural(id)
  if (!!pe !== !!pi) fail(`plural form mismatch for ${key}`)
  const base = constName(key)
  if (pe) ['ZERO', 'ONE', 'OTHER'].forEach((suffix, i) => add(`${base}_${suffix}`, pe[i], pi[i], key))
  else add(base, en, id, key)
}

const src = `// GENERATED by scripts/gen-strings.mjs from the web locales and i18n/mobile.*.json. Do not edit.
package com.zuramai.rencana.i18n

/**
 * Every UI string in English and Indonesian. Entry names are the dotted web i18n keys in UPPER_SNAKE
 * (\`travel.tripCount\` -> [TRAVEL_TRIP_COUNT_ZERO]/[TRAVEL_TRIP_COUNT_ONE]/[TRAVEL_TRIP_COUNT_OTHER]).
 * Use [com.zuramai.rencana.i18n.t] in composables. Placeholders look like \`{name}\`.
 */
enum class S(val en: String, val id: String) {
${entries.join(',\n')};
}
`
mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, src)
console.log(`gen-strings: wrote ${entries.length} entries`)
